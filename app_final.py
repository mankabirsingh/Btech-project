"""
app_final.py

Streamlit Web Interface for AI Security Scanner:
Presentation-Focused Dashboard for B.Tech Project

Designed for simple, clear presentation:
- Tab 1: Live Scanner (Effortless code inspection, preset examples, clear verdicts)
- Tab 2: Project Results (Headline achievements, benchmark comparison, research takeaways)
- Tab 3: System Overview (Multi-modal architecture, decision policy, technology stack)
"""

import sys
import json
from pathlib import Path
import pandas as pd
import streamlit as st

PROJECT_ROOT = Path(__file__).resolve().parent
sys.path.append(str(PROJECT_ROOT))

# Page configuration (No emojis)
st.set_page_config(
    page_title="AI Security Vulnerability Scanner",
    layout="wide",
    initial_sidebar_state="collapsed",
)

RESULTS_P11_DIR = PROJECT_ROOT / "results" / "p11"
RESULTS_P10_DIR = PROJECT_ROOT / "results" / "p10"
REPORTS_DIR = PROJECT_ROOT / "reports"
EXAMPLES_DIR = PROJECT_ROOT / "examples"


@st.cache_resource
def get_scanner():
    from src.inference_final import SecurityScanner
    return SecurityScanner(load_model_b=True)


# Preset Examples
EXAMPLES = {
    "Example 1: Vulnerable Code (Memory Deallocation / Use-After-Free)": {
        "file": "vulnerable.c",
        "description": "Real-world PHP runtime function with improper memory deallocation and potential use-after-free.",
    },
    "Example 2: Safe Code (Bounds-Checked Buffer)": {
        "file": "fixed.c",
        "description": "Safe C string copy with explicit buffer bounds check and null termination.",
    },
    "Example 3: Borderline Code (Mixed C++ Packet Parser)": {
        "file": "mixed.cpp",
        "description": "Modern C++ class mixing safe STL logic with legacy heap packet parsing.",
    },
}

# Initialize session state for code input
if "code_input" not in st.session_state:
    p_init = EXAMPLES_DIR / EXAMPLES["Example 1: Vulnerable Code (Memory Deallocation / Use-After-Free)"]["file"]
    st.session_state["code_input"] = p_init.read_text() if p_init.exists() else ""


def on_example_change():
    choice = st.session_state.get("example_choice")
    if choice in EXAMPLES:
        p = EXAMPLES_DIR / EXAMPLES[choice]["file"]
        if p.exists():
            st.session_state["code_input"] = p.read_text()
    elif choice == "Custom Code (Write or Paste)":
        st.session_state["code_input"] = (
            "int process_data(const char *input) {\n"
            "    char buf[64];\n"
            "    strcpy(buf, input);\n"
            "    return 0;\n"
            "}"
        )


# Header Section
st.title("AI Security Vulnerability Scanner")
st.markdown(
    "**B.Tech Project | Automated Security Analysis of C and C++ Source Code**  \n"
    "*By Mankabir Singh & Mohnish Gautam*"
)
st.markdown(
    "This system combines modern deep learning representations with static analysis tools "
    "to automatically inspect C/C++ code, distinguish safe code from critical security risks, "
    "and route ambiguous cases to human reviewers."
)
st.markdown("---")

# Navigation Tabs (No emojis)
tab_scan, tab_results, tab_overview = st.tabs(["Live Scanner", "Project Results", "System Overview"])


# ==============================================================================
# TAB 1: LIVE SCANNER
# ==============================================================================
with tab_scan:
    st.subheader("Interactive Code Inspection")
    st.markdown(
        "Select a pre-loaded code example below or write custom C/C++ code to evaluate its security risk."
    )

    col_select, col_empty = st.columns([2, 1])
    with col_select:
        example_choice = st.selectbox(
            "Select an Example to Test:",
            [
                "Example 1: Vulnerable Code (Memory Deallocation / Use-After-Free)",
                "Example 2: Safe Code (Bounds-Checked Buffer)",
                "Example 3: Borderline Code (Mixed C++ Packet Parser)",
                "Custom Code (Write or Paste)",
            ],
            key="example_choice",
            on_change=on_example_change,
        )

    col_code, col_opts = st.columns([2, 1])

    with col_code:
        code_input = st.text_area(
            "C / C++ Source Code:",
            key="code_input",
            height=280,
        )
        scan_button = st.button("Analyze Code", type="primary", use_container_width=True)

    with col_opts:
        st.markdown("**Analysis Configuration**")
        st.markdown(
            "- **Neural Models**: Qwen-2.5-Coder (0.5B) + CodeBERT  \n"
            "- **Static Analyzers**: Cppcheck + Flawfinder  \n"
            "- **Decision Rule**: 3-Way Triage (Safe / Unsure / Vulnerable)"
        )

        with st.expander("AI Code Provenance (Optional)", expanded=False):
            st.caption("Adjust risk estimation based on generative model metadata.")
            prov_active = st.checkbox("Code was generated by AI", value=False)
            prov_model = st.selectbox("AI Generator Model", ["claude-3-5-sonnet", "gpt-4o", "qwen-2.5-coder-32b"])
            prov_temp = st.slider("Sampling Temperature", min_value=0.0, max_value=1.0, value=0.2, step=0.1)

    if scan_button:
        if not code_input.strip():
            st.warning("Please provide C or C++ source code to inspect.")
        else:
            with st.spinner("Analyzing code with neural encoders and static analyzers..."):
                scanner = get_scanner()

                prov_dict = None
                if prov_active:
                    prov_dict = {
                        "model": prov_model,
                        "temperature": prov_temp,
                        "prompt": "Security sensitive routine",
                        "role": "ai_t02" if prov_temp <= 0.3 else "ai_t08",
                    }

                report = scanner.scan_code(code_input, provenance=prov_dict)

            st.markdown("---")
            st.markdown("### Analysis Findings")

            verdict = report["verdict"]
            p_code = report["p_code"]
            prec = report["calibrated_precision_at_score"]
            npv = report["calibrated_npv_at_score"]

            # Clear Verdict Banner
            if verdict == "VULNERABLE":
                st.error(
                    "**Verdict: VULNERABLE**  \n"
                    "High probability of a security flaw. Recommended action: Do not deploy without refactoring."
                )
            elif verdict == "SAFE":
                st.success(
                    "**Verdict: SAFE**  \n"
                    "No critical vulnerability patterns detected. High confidence of safe implementation."
                )
            else:
                st.warning(
                    "**Verdict: UNSURE (Needs Manual Review)**  \n"
                    "Ambiguous risk score. Recommended action: Forward to security queue for manual inspection."
                )

            # High-level Metric Cards
            m1, m2, m3, m4 = st.columns(4)
            with m1:
                st.metric("Vulnerability Risk", f"{p_code * 100:.1f}%")
            with m2:
                if verdict == "SAFE":
                    st.metric("Safety Reliability (NPV)", f"{npv * 100:.1f}%")
                else:
                    st.metric("Flaw Precision", f"{prec * 100:.1f}%")
            with m3:
                st.metric("Code Length", f"{report['length_tokens']} tokens")
            with m4:
                st.metric("Scan Speed", f"{report['runtime_ms']:.0f} ms")

            # Suspected Vulnerability Categories
            st.markdown("#### Likely Vulnerability Types")
            if report.get("likely_cwe"):
                cols_cwe = st.columns(min(len(report["likely_cwe"]), 3))
                for i, (cwe_name, cwe_prob) in enumerate(report["likely_cwe"][:3]):
                    with cols_cwe[i]:
                        st.progress(float(cwe_prob), text=f"{cwe_name}: {cwe_prob*100:.1f}% probability")
            else:
                st.markdown("No specific vulnerability class flagged.")

            # Flagged Lines of Code
            st.markdown("#### Line-by-Line Attribution")
            suspicious = report.get("suspicious_lines", [])
            if suspicious:
                st.markdown(
                    f"Neural sensitivity analysis identified **{len(suspicious)} lines** "
                    f"that contributed most strongly to the predicted risk: "
                    + ", ".join([f"Line {l}" for l in suspicious])
                )
                lines = code_input.splitlines()
                annotated = []
                for idx, line in enumerate(lines):
                    line_no = idx + 1
                    if line_no in suspicious:
                        annotated.append(f"{line_no:3d}  >>> [FLAGGED] {line}")
                    else:
                        annotated.append(f"{line_no:3d}            {line}")
                st.code("\n".join(annotated), language="cpp")
            else:
                st.markdown("No single line was disproportionately responsible for the risk score.")

            # Static Tool Output
            st.markdown("#### Static Tool Findings")
            findings = report.get("static_findings", [])
            if findings:
                df_findings = pd.DataFrame(findings)[["tool", "cwe", "line", "message"]]
                df_findings.columns = ["Tool", "Vulnerability Class", "Line", "Warning Message"]
                st.dataframe(df_findings, use_container_width=True)
            else:
                st.info("Cppcheck and Flawfinder reported no syntax or rule violations.")

            st.caption(
                "Advisory Note: This system is designed for security triage assistance. "
                "All critical code should be verified by human engineers before deployment."
            )


